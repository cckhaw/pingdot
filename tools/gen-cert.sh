#!/bin/sh
# Makes a self-signed TLS certificate for the ESP32.
#   ./tools/gen-cert.sh <your-public-hostname-or-ip>
# Writes firmware/ledmatrix/cert.h (certificate + private key for the sketch, git-ignored) and
# tools/device-cert.pem (public certificate for Vercel, git-ignored), and prints the Vercel value.
set -e
HOST="${1:?usage: $0 <public-hostname-or-ip>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 -subj "/CN=$HOST" \
  -keyout "$T/key.pem" -out "$T/cert.pem" 2>/dev/null
openssl x509 -in "$T/cert.pem" -outform DER -out "$T/cert.der"
openssl rsa -in "$T/key.pem" -outform DER -out "$T/key.der" 2>/dev/null

array() {  # name file
  echo "unsigned char $1[] = {"
  od -An -v -tx1 "$2" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
  echo "};"
  echo "unsigned int $1_len = $(wc -c < "$2" | tr -d ' ');"
}
{
  echo "// Generated by tools/gen-cert.sh - contains your private key, do not share or commit."
  array cert_der "$T/cert.der"
  array key_der "$T/key.der"
} > "$ROOT/firmware/ledmatrix/cert.h"

cp "$T/cert.pem" "$ROOT/tools/device-cert.pem"
echo "Wrote firmware/ledmatrix/cert.h and tools/device-cert.pem"
echo
echo "Vercel env var DEVICE_CERT_PEM (paste exactly this line):"
awk 'NF { printf "%s\\n", $0 }' "$T/cert.pem"
echo
